import assert from 'node:assert/strict';
import worker, { Wall, Drafts } from './worker.js';
const state = () => { const data = new Map(); const storage = { get: async k => data.get(k), put: async (k,v) => data.set(k,v), delete: async k => data.delete(k), list: async ({prefix}) => new Map([...data].filter(([k])=>k.startsWith(prefix))), transaction: async fn => fn(storage) }; return { storage }; };
let mail;
const env = { DRAFT_KEY: 'test-owner-secret', REVIEW_EMAIL: { send: async message => { mail = message; } }, API_RATE_LIMITER: { limit: async () => ({success:true}) } };
const wall = new Wall(state(),env), drafts = new Drafts(state(),env);
const binding = obj => ({idFromName:x=>x, get:()=>({fetch:(req,init)=>obj.fetch(req instanceof Request?req:new Request(req,init))})});
env.WALL=binding(wall); env.DRAFTS=binding(drafts);
const req=(path, method='GET', body, cookie) => new Request('https://burcs.dev'+path, {method, headers:{origin:'https://burcs.dev', 'content-type':'application/json', ...(cookie?{cookie}:{})}, ...(body?{body:JSON.stringify(body)}:{})});
assert.equal((await worker.fetch(req('/api/review-link','POST'),env)).status,404);
const issue=req('/internal/review-token','POST');
issue.headers.set('x-draft-key',env.DRAFT_KEY);
const {token}=await (await wall.fetch(issue)).json();
const session=await worker.fetch(req('/api/review-session','POST',{token}),env);
assert.equal(session.status,200);
const cookie=session.headers.get('set-cookie').split(';')[0];
assert.match(session.headers.get('set-cookie'),/HttpOnly; Secure; SameSite=Strict/);
assert.equal((await worker.fetch(req('/api/review-session','POST',{token}),env)).status,403);
assert.equal((await worker.fetch(req('/api/wall?pending'),env)).status,403);
assert.equal((await worker.fetch(req('/api/wall?pending','GET',null,cookie),env)).status,200);
assert.equal((await worker.fetch(req('/api/draft/annotations?slug=notes/test&pending','GET',null,cookie),env)).status,200);
assert.equal((await worker.fetch(req('/api/draft?slug=notes/test','PUT',{html:'test'},cookie),env)).status,403);
assert.equal((await worker.fetch(req('/api/wall?pending','GET',null,cookie+'x'),env)).status,403);
console.log('PASS: email destination, one-time login, private cookie, owner queue, anonymous denial, tamper denial, and no draft editing permission.');
const doodle = {kind:'doodle', name:'Visitor', page:'/wall/', w:816, h:1056, strokes:[[200,200,0.5,220,230,0.5]]};
assert.equal((await worker.fetch(req('/api/wall','POST',{...doodle,page:'/'}),env)).status,400);
assert.equal((await worker.fetch(req('/api/wall','POST',{...doodle,page:'/projects/'}),env)).status,400);
assert.equal((await worker.fetch(req('/api/wall','POST',doodle),env)).status,200);
assert.equal(mail.to,'brandonstrittmatter@gmail.com');
assert.match(mail.text,/https:\/\/burcs.dev\/wall\/\?sheet=1&review=[^#\s]+#review=/);
const comment=await worker.fetch(req('/api/draft/annotations?slug=notes/test','POST',{kind:'comment',quote:'test',text:'An interesting thought.',name:'Visitor'}),env);
assert.equal(comment.status,200);
assert.match(mail.text,/https:\/\/burcs.dev\/notes\/test\/\?review=[^#\s]+#review=/);
const legacyState=state();
await legacyState.storage.put('d:/projects/|old',{...doodle,page:'/projects/',id:'old',approved:1});
await legacyState.storage.put('p:queued',{...doodle,page:'/',id:'queued'});
const legacyWall=new Wall(legacyState,env);
await legacyWall.fetch(req('/api/wall?page=/wall/'));
assert.equal(await legacyState.storage.get('d:/projects/|old'),undefined);
assert.equal((await legacyState.storage.get('d:/wall/|old')).page,'/wall/');
assert.equal((await legacyState.storage.get('p:queued')).page,'/wall/');
assert.deepEqual((await (await legacyWall.fetch(req('/api/wall?page=/projects/'))).json()).items,[]);
const approve=req('/api/wall/approve?id=queued','POST');
approve.headers.set('x-draft-key',env.DRAFT_KEY);
assert.equal((await legacyWall.fetch(approve)).status,200);
assert.equal((await legacyState.storage.get('d:/wall/|queued')).page,'/wall/');
console.log('PASS: wall-only submissions, legacy migration, approval destination, and no off-wall display.');
assert.equal((await worker.fetch(req('/api/wall/sheets','POST'),env)).status,403);
const added=await worker.fetch(req('/api/wall/sheets','POST',null,cookie),env);
assert.equal(added.status,200);
assert.equal((await added.json()).sheets,2);
const newDoodle=req('/api/wall','POST',{...doodle,sheet:2});
newDoodle.headers.set('x-draft-key',env.DRAFT_KEY);
const submitted=await worker.fetch(newDoodle,env);
assert.equal(submitted.status,200);
const newId=(await submitted.json()).id;
assert.equal((await worker.fetch(req(`/api/wall/approve?id=${newId}&sheet=2`,'POST',null,cookie),env)).status,200);
const pageOne=await (await worker.fetch(req('/api/wall?page=/wall/&sheet=1'),env)).json();
const pageTwo=await (await worker.fetch(req('/api/wall?page=/wall/&sheet=2'),env)).json();
assert.equal(pageOne.items.some(x=>x.id===newId),false);
assert.equal(pageTwo.items.some(x=>x.id===newId),true);
assert.equal((await worker.fetch(req(`/api/wall/sheet?id=${newId}`,'PATCH',{sheet:99},cookie),env)).status,400);
assert.equal((await worker.fetch(req(`/api/wall/sheet?id=${newId}`,'PATCH',{sheet:1},cookie),env)).status,200);
assert.equal((await (await worker.fetch(req('/api/wall?page=/wall/&sheet=2'),env)).json()).items.length,0);
console.log('PASS: owner-only page creation, page-specific approval/display, moving doodles, and invalid page rejection.');
